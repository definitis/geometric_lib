def area(a, h):
    """Вычисляет площадь треугольника по стороне a и проведенной к ней высоте h.

    Формула: S = (a * h) / 2.
    Параметры a и h должны быть положительными числами (int или float).

    >>> area(6, 5)
    15.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """Вычисляет периметр треугольника по трем сторонам a, b, c.

    Формула: P = a + b + c.
    Параметры a, b, c должны быть длинами сторон существующего треугольника.

    >>> perimeter(4, 5, 6)
    15
    """
    return a + b + c
