def area(a, b):
    """Вычисляет площадь прямоугольника по двум сторонам a и b.

    Формула: S = a * b.
    Параметры a и b должны быть положительными числами (int или float).

    >>> area(4, 6)
    24
    """
    return a * b


def perimeter(a, b):
    """Вычисляет периметр прямоугольника по двум сторонам a и b.

    Формула: P = 2 * (a + b).
    Параметры a и b должны быть положительными числами (int или float).

    >>> perimeter(4, 6)
    20
    """
    return 2 * (a + b)
