def area(a):
    """Вычисляет площадь квадрата по длине его стороны a.

    Формула: S = a^2.
    Параметр a должен быть положительным числом (int или float).

    >>> area(5)
    25
    """
    return a * a


def perimeter(a):
    """Вычисляет периметр квадрата по длине его стороны a.

    Формула: P = 4 * a.
    Параметр a должен быть положительным числом (int или float).

    >>> perimeter(5)
    20
    """
    return 4 * a
