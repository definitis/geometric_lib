import math


def area(r):
    """Вычисляет площадь круга по заданному радиусу r.

    Формула: S = pi * r^2.
    Параметр r должен быть положительным числом (int или float).

    >>> round(area(3), 4)
    28.2743
    """
    return math.pi * r * r


def perimeter(r):
    """Вычисляет длину окружности (периметр круга) по заданному радиусу r.

    Формула: P = 2 * pi * r.
    Параметр r должен быть положительным числом (int или float).

    >>> round(perimeter(3), 4)
    18.8496
    """
    return 2 * math.pi * r
